import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import ts from 'typescript';

const normalized = value => value.split(path.sep).join('/');
const comment = value => typeof value === 'string' ? value : ts.displayPartsToString(value ?? []);
const exported = node => node.modifiers?.some(m => m.kind === ts.SyntaxKind.ExportKeyword);

function readComponents(file, root) {
  const source = ts.createSourceFile(file, fs.readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  if (source.parseDiagnostics.length) throw new Error(`Không đọc được TypeScript: ${file}`);
  const types = new Map(source.statements.filter(node => ts.isTypeAliasDeclaration(node) && exported(node)).map(node => [node.name.text, node.getText(source)]));
  const components = [];
  for (const statement of source.statements) {
    if (ts.isExportAssignment(statement) || (exported(statement) && ts.isFunctionDeclaration(statement) && !statement.name)) {
      throw new Error(`${normalized(path.relative(root, file))}: UI component cần export có tên để sinh import và tài liệu chính xác.`);
    }
    if (!exported(statement)) continue;
    const names = ts.isFunctionDeclaration(statement) ? [statement.name?.text] : ts.isVariableStatement(statement)
      ? statement.declarationList.declarations.map(declaration => ts.isIdentifier(declaration.name) ? declaration.name.text : undefined) : [];
    for (const name of names.filter(name => name && /^[A-Z]/.test(name))) {
      const doc = statement.jsDoc?.at(-1);
      const summary = comment(doc?.comment).trim();
      const tags = doc?.tags ?? [];
      const example = tags.filter(tag => tag.tagName.text === 'example').map(tag => comment(tag.comment).trim()).join('\n\n');
      const remarks = tags.filter(tag => tag.tagName.text === 'remarks').map(tag => comment(tag.comment).trim()).join('\n\n');
      if (!summary || !example || !remarks) throw new Error(`${normalized(path.relative(root, file))}: ${name} cần JSDoc mô tả, @remarks và @example. Thêm tài liệu cạnh component rồi chạy npm run docs:ui.`);
      const props = types.get(`${name}Props`);
      if (!props) throw new Error(`${name}: khai báo export type ${name}Props để tài liệu API theo kịp source.`);
      const relative = normalized(path.relative(root, file));
      const first = source.statements[0];
      const mode = first && ts.isExpressionStatement(first) && ts.isStringLiteral(first.expression) && first.expression.text === 'use client'
        ? 'Client Component' : 'Không khai báo use client; xem lưu ý sử dụng bên dưới';
      const fingerprint = createHash('sha256').update(source.text.replace(/\r\n/g, '\n')).digest('hex');
      components.push({ name, file: relative, summary, remarks, example, props, mode, fingerprint });
    }
  }
  return components;
}

export function renderUiDocs(root = process.cwd()) {
  const base = path.join(root, 'src/components/ui');
  const folders = [];
  function visit(folder) {
    folders.push(folder);
    for (const entry of fs.readdirSync(folder, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) if (entry.isDirectory()) visit(path.join(folder, entry.name));
  }
  visit(base);
  const output = new Map();
  {
    const components = folders.flatMap(folder => fs.readdirSync(folder, { withFileTypes: true })
      .sort((a, b) => a.name.localeCompare(b.name))
      .filter(entry => entry.isFile() && /\.tsx?$/.test(entry.name) && !/\.(test|spec|d)\.tsx?$/.test(entry.name))
      .flatMap(entry => readComponents(path.join(folder, entry.name), root)));
    const title = normalized(path.relative(root, base));
    let text = `# ${title}\n\n<!-- GENERATED by scripts/ui-docs.mjs. Update JSDoc in component source, then run npm run docs:ui. -->\n\nComponent tái sử dụng, không chứa API/nghiệp vụ. Sửa JSDoc cạnh component; dev/build tự cập nhật file này.\n\n`;
    for (const c of components) {
      const sourceLink = normalized(path.relative(base, path.join(root, c.file)));
      text += `## ${c.name}\n\n<!-- source-sha256: ${c.fingerprint} -->\n\n${c.summary} [${c.name}Props](./${sourceLink}).\n\n${c.remarks}\n\n\`\`\`tsx\n${c.example}\n\`\`\`\n\n`;
    }
    if (!components.length) text += 'Chưa có component được export.\n';
    output.set(path.join(base, 'README.md'), text.trimEnd() + '\n');
  }
  return output;
}

export function updateUiDocs({ root = process.cwd(), check = false } = {}) {
  const output = renderUiDocs(root);
  const stale = [];
  for (const [file, content] of output) {
    if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) continue;
    if (check) stale.push(normalized(path.relative(root, file)));
    else fs.writeFileSync(file, content);
  }
  if (stale.length) throw new Error(`Tài liệu UI lỗi thời: ${stale.join(', ')}. Chạy npm run docs:ui.`);
  return output.size;
}

export function watchUiDocs(root = process.cwd()) {
  updateUiDocs({ root });
  let timer;
  const watcher = fs.watch(path.join(root, 'src/components/ui'), { recursive: true }, (_event, file) => {
    if (!file || !/\.tsx?$/.test(file)) return;
    clearTimeout(timer);
    timer = setTimeout(() => {
      try { updateUiDocs({ root }); console.log('[docs] Đã cập nhật tài liệu UI.'); }
      catch (error) { console.error('[docs]', error.message); }
    }, 150);
  });
  return () => { clearTimeout(timer); watcher.close(); };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try {
    if (process.argv.includes('--watch')) { watchUiDocs(); console.log('[docs] Đang theo dõi source UI.'); }
    else { const count = updateUiDocs({ check: process.argv.includes('--check') }); console.log(`[docs] ${count} tài liệu UI hợp lệ.`); }
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
