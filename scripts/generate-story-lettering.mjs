import fs from "node:fs";
import { createRequire } from "node:module";
import { vi } from "../src/i18n/locales/vi.ts";
import { en } from "../src/i18n/locales/en.ts";

// The font parser already ships with the installed Next.js version. It is only
// used here; generated paths need no font download or parser in the browser.
const require = createRequire(import.meta.url);
const createFont = require("next/dist/compiled/@next/font/dist/fontkit").default;
const font = createFont(fs.readFileSync(new URL("./assets/story-lettering/Allura-Regular.ttf", import.meta.url)));
const scale = 100 / font.unitsPerEm;

function lettering(dictionary) {
  const lines = [dictionary.story.heading_line1, dictionary.story.heading_line2];
  const runs = lines.map(text => font.layout(text));
  const widths = runs.map(run => run.positions.reduce((sum, position) => sum + position.xAdvance, 0) * scale);
  const width = Math.ceil(Math.max(...widths) + 48);
  return {
    width,
    height: 240,
    lines: runs.map((run, index) => {
      let cursor = (width - widths[index]) / 2;
      const paths = run.glyphs.flatMap((glyph, glyphIndex) => {
        const position = run.positions[glyphIndex];
        const path = glyph.path.scale(scale, -scale).translate(cursor + position.xOffset * scale, 82 + index * 105 - position.yOffset * scale);
        cursor += position.xAdvance * scale;
        return path.toSVG() ? [path] : [];
      });
      const left = Math.min(...paths.map(path => path.bbox.minX));
      const right = Math.max(...paths.map(path => path.bbox.maxX));
      const centerOffset = width / 2 - (left + right) / 2;
      const glyphs = paths.map(path => path.translate(centerOffset, 0).toSVG()
        .replace(/-?\d+\.\d{3,}/g, value => String(Number(Number(value).toFixed(2)))));
      return { text: lines[index], glyphs };
    }),
  };
}

const output = `// Generated by scripts/generate-story-lettering.mjs. Allura is licensed under OFL; see scripts/assets/story-lettering/OFL.txt.
import type { Locale } from "../i18n/types";

export type StoryLettering = {
  width: number;
  height: number;
  lines: { text: string; glyphs: string[] }[];
};

const lettering: Record<Locale, StoryLettering> = ${JSON.stringify({ vi: lettering(vi), en: lettering(en) }, null, 2)};

export function getStoryLettering(locale: Locale): StoryLettering { return lettering[locale]; }
`;
fs.writeFileSync(new URL("../src/config/story-lettering.ts", import.meta.url), output);
console.log("Generated Vietnamese and English story lettering.");
